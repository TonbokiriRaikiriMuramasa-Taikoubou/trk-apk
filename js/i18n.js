let lang = "ja";
function tr(key, vars) {
  let s = (TEXT[lang] && TEXT[lang][key]) ?? TEXT.en[key] ?? TEXT.ja[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
